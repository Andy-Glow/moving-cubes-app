/**
 * Интерфейс, описывающий структуру данных одного кубика.
 * Используется для того, чтобы TypeScript контролировал правильность данных в стейте и пропсах.
 */
export interface Cube {
  id: string; // Уникальный идентификатор кубика (например, "cube-1")
  x: number; // Текущая координата кубика по горизонтальной оси X (в пикселях)
  y: number; // Текущая координата кубика по вертикальной оси Y (в пикселях)
  size: number; // Размер кубика (ширина и высота равны, так как это квадрат)
  color: string; // Текущий цвет кубика в формате HEX (например, "#a78bfa")
}

/**
 * Тип для цвета кубика.
 * По сути является строкой, но выделение в отдельный тип делает код более читаемым.
 */
export type CubeColor = string;
